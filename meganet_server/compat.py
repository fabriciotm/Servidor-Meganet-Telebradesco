def resolve_legacy_server_export(name: str) -> object:
    """Resolve one historical ``server.<name>`` attribute on demand."""
    target = LEGACY_SERVER_EXPORTS.get(name)
    if target is None:
        raise AttributeError(name)
    module_name, attribute_name = target
    module = importlib.import_module(module_name, package=__package__)
    return getattr(module, attribute_name)

def legacy_server_dir() -> tuple[str, ...]:
    """Return the names maintained by the legacy compatibility facade."""
    return tuple(sorted(LEGACY_SERVER_EXPORTS))
